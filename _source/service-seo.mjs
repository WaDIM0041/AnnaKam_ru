function swap(html, selector, replacement) {
  if (!selector.test(html)) throw new Error('SEO template anchor missing: ' + selector);
  return html.replace(selector, replacement);
}

function metadata(html, title, description) {
  return html
    .replace(/<title>[^<]*<\/title>/, '<title>' + title + '</title>')
    .replace(/(<meta (?:property|name)="(?:og:title|twitter:title)" content=")[^"]*/g, '$1' + title)
    .replace(/(<meta (?:property|name)="(?:description|og:description|twitter:description)" content=")[^"]*/g, '$1' + description);
}

